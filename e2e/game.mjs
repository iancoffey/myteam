// One coach, U6 team: start a game in one tap, check in, run it, end & save; practice with the drill
// timer; discard a game from the menu and from the team page.
import { OUT, createTeam, fail, phones, secs, signup, step } from './helpers.mjs'

const { pages: [page], done } = await phones(1)

await signup(page, 'game-coach@example.com', { club: 'Riverside Youth Soccer' })
step('signed up and created a club')
const teamUrl = await createTeam(page, { name: 'Green Rockets', age: 'U6', roster: ['Leo', 'Ava', 'Sam', 'Noah', 'Maya', 'Eli'] })
if (/schedule|snack|parent/i.test(await page.locator('main').innerText())) fail('team page mentions schedule/snacks/parents')
step('team created; no schedule, snacks or parents')

await page.goto(`${teamUrl}/roster`)
await page.fill('#names', 'Zoe')
await page.click('button:has-text("Add kids")')
await page.locator('.kid-name', { hasText: 'Zoe' }).waitFor()
step('kid added on the roster')

await page.goto(teamUrl)
await page.click('button:has-text("Start game")')
await page.getByText('Who’s here?').first().waitFor()
for (const n of ['Leo', 'Ava', 'Sam', 'Noah', 'Maya']) await page.click(`.tile:has-text("${n}")`)
await page.click('button:has-text("Make lineup")')
await page.getByText('Starting lineup').waitFor()
step('Start game → check-in → lineup: ' + (await page.$$eval('.group-h span:first-child', (s) => s.map((x) => x.textContent))).join(' | '))

const label = await page.locator('.start-btn').innerText()
await page.click('.start-btn')
await page.waitForTimeout(3200)
const t = await page.locator('.clock .time').innerText()
if (!(secs(t) <= 237 && secs(t) >= 233)) fail('clock not counting down: ' + t)
step(`"${label}" → clock counting down (${t})`)
await page.screenshot({ path: `${OUT}game-running.png` })

await page.click('.tile:has-text("Eli")')
await page.getByText('Eli is here').first().waitFor()
await page.click('button:has-text("Undo")')
await page.getByText('Undone: Eli is here').first().waitFor()
await page.click('.tile:has-text("Eli")')
await page.click('button.goal:has-text("+ Us")')
step('late arrival, undo, re-arrive, goal')

await page.click('.clock-strip .end:has-text("End period 1")')
await page.getByText('End of Period 1 of 8').first().waitFor()
await page.click('.go-btn:has-text("Swap")')
await page.click('.start-btn:has-text("Start P2")')
await page.getByText('Running').first().waitFor()
step('ended period 1, swapped at the break, started period 2')

await page.click('button[aria-label="Menu"]')
await page.click('button:has-text("End game & save")')
await page.getByText('Season minutes · 1 game').waitFor()
await page.locator('button:has-text("Start game")').waitFor()
await page.locator('a.link-row', { hasText: 'subs by period' }).click()
await page.getByRole('heading', { name: 'Subs by period' }).waitFor()
step('End game & save → team page ready for the next session; saved game shows subs by period')

await page.goto(teamUrl)
await page.click('button:has-text("Practice")')
await page.getByRole('heading', { name: 'Practice' }).waitFor()
await page.click('.clock-strip button:has-text("5′")')
await page.click('.start-btn:has-text("Start")')
await page.waitForTimeout(2200)
const d = await page.locator('.clock .time').innerText()
if (!(secs(d) <= 298 && secs(d) >= 296)) fail('drill timer not counting: ' + d)
await page.click('.tile:has-text("Ava")')
await page.click('.start-btn:has-text("Pause")')
await page.click('.cta button:has-text("End practice")')
await page.locator('button:has-text("Start game")').waitFor()
step(`practice: 5′ drill timer ran (${d}), check-in during practice, End practice`)

await page.click('button:has-text("Start game")')
await page.getByText('Who’s here?').first().waitFor()
await page.click('button[aria-label="Menu"]')
await page.click('button:has-text("Discard this game")')
await page.click('button:has-text("Tap again to discard")')
await page.locator('button:has-text("Start game")').waitFor()
await page.click('button:has-text("Start game")')
await page.getByText('Who’s here?').first().waitFor()
await page.click('a[aria-label^="Back to team"]')
await page.getByText('Game in progress').waitFor()
await page.click('.live-card button:has-text("Discard")')
await page.click('.live-card button:has-text("Tap again to discard")')
await page.locator('button:has-text("Start game")').waitFor()
await page.getByText('Season minutes · 1 game').waitFor()
step('discarded games from the menu and from the team page; nothing saved')

await done()
